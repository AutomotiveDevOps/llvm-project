DecodeStatus PPCDisassembler::getInstruction(MCInst &MI, uint64_t &Size,
                                             ArrayRef<uint8_t> Bytes,
                                             uint64_t Address,
                                             raw_ostream &CS) const {
  auto *ReadFunc = IsLittleEndian ? support::endian::read32le
                                  : support::endian::read32be;
  auto *ReadFunc16 = IsLittleEndian ? support::endian::read16le
                                    : support::endian::read16be;

  // If this is an 8-byte prefixed instruction, handle it here.
  // Note: prefixed instructions aren't technically 8-byte entities - the prefix
  //       appears in memory at an address 4 bytes prior to that of the base
  //       instruction regardless of endianness. So we read the two pieces and
  //       rebuild the 8-byte instruction.
  // TODO: In this function we call decodeInstruction several times with
  //       different decoder tables. It may be possible to only call once by
  //       looking at the top 6 bits of the instruction.
  if (STI.hasFeature(PPC::FeaturePrefixInstrs) && Bytes.size() >= 8) {
    uint32_t Prefix = ReadFunc(Bytes.data());
    uint32_t BaseInst = ReadFunc(Bytes.data() + 4);
    uint64_t Inst = BaseInst | (uint64_t)Prefix << 32;
    DecodeStatus result = decodeInstruction(DecoderTable64, MI, Inst, Address,
                                            this, STI);
    if (result != MCDisassembler::Fail) {
      Size = 8;
      return result;
    }
  }

  // Try VLE instruction decoding if VLE is enabled.
  // VLE instructions can be 16-bit (se_ prefix) or 32-bit (e_ prefix).
  // 16-bit VLE instructions are identified by their opcode patterns.
  if (STI.getFeatureBits()[PPC::FeatureVLE]) {
    // We need at least 2 bytes to determine if it's a VLE instruction
    if (Bytes.size() >= 2) {
      uint16_t Inst16 = ReadFunc16(Bytes.data());
      
      // Try decoding as VLE 16-bit instruction first
      // Check for VLE 16-bit instruction patterns:
      // - C form: bits 0-15 are the instruction (se_illegal, se_isync, etc.)
      // - SE_R/SE_RR forms: bits 10-15 contain opcode
      // - SD4 form: bits 12-15 contain opcode (0x8-0xD for load/store)
      // - BD8 form: bits 11-15 contain opcode (0x1C for branches)
      
      // Check if this looks like a VLE 16-bit instruction
      // VLE instructions have specific opcode ranges
      uint16_t OpcodeBits = Inst16 & 0xFC00;  // Top 6 bits (opcode field)
      uint16_t OpcodeTop4 = (Inst16 >> 12) & 0xF;  // Top 4 bits for SD4 form
      
      // Try decoding with VLE decoder table (will be generated by TableGen)
      // For now, we'll decode manually for known VLE opcodes
      // Note: Full decoder table generation requires TableGen to process VLE instructions
      
      // Decode known VLE instruction patterns
      // C form instructions (opcode in bits 0-15)
      if ((Inst16 & 0xFFFF) <= 0x000C) {
        // Simple C form instructions (se_illegal=0, se_isync=1, se_sc=2, etc.)
        // These will be handled by the generated decoder table
      }
      
      // SD4 form (load/store) - opcode in bits 12-15
      if (OpcodeTop4 >= 0x8 && OpcodeTop4 <= 0xD) {
        // se_lbz (0x8), se_stb (0x9), se_lhz (0xA), se_sth (0xB),
        // se_lwz (0xC), se_stw (0xD)
        // Will be handled by decoder table
      }
      
      // SE_RR/SE_R/SE_IM5 forms - opcode in bits 10-15
      if (OpcodeBits >= 0x2600 && OpcodeBits <= 0x27FF) {
        // SE_RR form instructions
        // Will be handled by decoder table
      }
      
      // Try the decoder table (if it exists - TableGen will generate it)
      // For now, fall through to let standard decoder try
      // TODO: Once TableGen generates DecoderTableVLE16, use it here
    }
  }

  // Get the four bytes of the instruction.
  Size = 4;
  if (Bytes.size() < 4) {
    Size = 0;
    return MCDisassembler::Fail;
  }

  // Read the instruction in the proper endianness.
  uint64_t Inst = ReadFunc(Bytes.data());
  uint32_t Inst32 = static_cast<uint32_t>(Inst);

  // When VLE is enabled, we need to distinguish between:
  // - VLE32 instructions (32-bit VLE with e_ prefix)
  // - BookE instructions (standard 32-bit PowerPC instructions)
  // According to AN4648, we can use the algorithm to check if a 32-bit
  // instruction is VLE32 or BookE when in a VLE context.
  // The algorithm checks bits 31 and 28: (upper_halfword & 0x9000) == 0x1000
  // to identify 32-bit VLE instructions.
  if (STI.getFeatureBits()[PPC::FeatureVLE]) {
    // Check if this is a 32-bit VLE instruction using AN4648 algorithm
    // Note: In real hardware, VLE vs BookE context is determined by MMU
    // page settings (MAS2[VLE] bit), but for disassembly we try both.
    if (PPC::isVLE32BitInstruction(Inst32)) {
      // This appears to be a 32-bit VLE instruction (e_ prefix)
      // Try decoding with VLE32 decoder table if it exists
      // TODO: Once TableGen generates DecoderTableVLE32, use it here
      // For now, fall through to standard decoding (VLE32 may decode
      // as standard instructions if no VLE32 decoder table is available)
    }
    // If not VLE32, it might be BookE (standard 32-bit) or could be
    // a 16-bit VLE that we failed to decode earlier
  }

  if (STI.hasFeature(PPC::FeatureSPE)) {
    DecodeStatus result =
        decodeInstruction(DecoderTableSPE32, MI, Inst, Address, this, STI);
    if (result != MCDisassembler::Fail)
      return result;
  }

  return decodeInstruction(DecoderTable32, MI, Inst, Address, this, STI);
}
